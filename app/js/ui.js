export function icon(name, cls = '', title = '') {
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '2');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', title ? 'false' : 'true');
  if (cls) svg.setAttribute('class', cls);
  svg.innerHTML = (title ? `<title>${title}</title>` : '') + PATHS[name];
  return svg;
}

let toastTimer;
export function toast(msg, kind = '') {
  const t = document.getElementById('toast');
  t.textContent = msg;
  t.className = kind;
  t.hidden = false;
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => { t.hidden = true; }, kind === 'err' ? 6000 : 3000);
}

/** Pannello modale; su telefono si apre dal basso. Restituisce l'elemento dialog. */
export function sheet(content) {
  const d = h('dialog', { class: 'sheet' }, content);
  document.body.append(d);
  d.addEventListener('close', () => d.remove());
  d.addEventListener('click', (e) => { if (e.target === d) d.close(); });
  d.showModal();
  return d;
}

export function loading(text = 'Caricamento…') {
  return h('div', { class: 'loading' }, h('div', { class: 'spinner' }), text);
}

/** Esegue un salvataggio mostrando lo stato e gestendo gli errori in modo uniforme. */
export async function withBusy(button, fn) {
  const label = button ? button.textContent : '';
  if (button) { button.disabled = true; button.textContent = 'Salvataggio…'; }
  try { return await fn(); }
  finally { if (button) { button.disabled = false; button.textContent = label; } }
}
